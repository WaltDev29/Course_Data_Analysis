import pandas as pd

# 1. 다음의 월평균기온 통계표를 판다스 데이터프레임에 저장하시오.
# (회색 음영 부분은 행과 열의 인덱스로 저장)
data = {
    '전북': [-0.1, 1.8, 6.4, 12.3, 17.9, 22.2],
    '전주': [0.0, 2.0, 6.8, 12.9, 18.5, 22.8],
    '군산': [-0.1, 1.6, 5.8, 11.5, 17.1, 21.6],
    '부안': [-0.2, 1.6, 5.9, 11.5, 17.1, 21.5]
}
index = ['1월', '2월', '3월', '4월', '5월', '6월']

temp = pd.DataFrame(data, index=index)
print("=== 1번 결과: 데이터프레임 ===")
print(temp)
print("\n")


# 2. 절대위치 인덱스를 이용하여 전주의 3월 평균 기온을 출력하시오.
# '3월'은 인덱스 2(세 번째 행), '전주'는 인덱스 1(두 번째 열)
ans2 = temp.iloc[2, 1]
print(f"2번: 전주의 3월 평균 기온 = {ans2}")


# 3. 절대위치 인덱스를 이용하여 부안의 4월 평균 기온을 출력하시오.
# '4월'은 인덱스 3(네 번째 행), '부안'은 인덱스 3(네 번째 열)
ans3 = temp.iloc[3, 3]
print(f"3번: 부안의 4월 평균 기온 = {ans3}")


# 4. 레이블 인덱스를 이용하여 군산의 1월 평균 기온을 출력하시오.
ans4 = temp.loc['1월', '군산']
print(f"4번: 군산의 1월 평균 기온 = {ans4}")


# 5. 레이블 인덱스를 이용하여 전북의 6월 평균 기온을 출력하시오.
ans5 = temp.loc['6월', '전북']
print(f"5번: 전북의 6월 평균 기온 = {ans5}")


# 6. 전주의 1월~6월 평균 기온만 시리즈로 뽑아 출력하시오.
print("\n=== 6번 결과: 전주의 평균 기온 (시리즈) ===")
ans6 = temp['전주']  # temp.loc[:, '전주'] 와 동일
print(ans6)


# 7. 4개 지역의 5월 평균 기온을 한 줄로 출력하시오.
print("\n=== 7번 결과: 4개 지역의 5월 평균 기온 ===")
ans7 = temp.loc['5월']
print(ans7)


# 8. 전주와 군산의 3월 기온 차이가 몇 도인지 계산해서 출력하시오.
# (부동소수점 오차 방지를 위해 round 함수 적용)
diff = round(temp.loc['3월', '전주'] - temp.loc['3월', '군산'], 1)
print(f"\n8번: 전주와 군산의 3월 기온 차이 = {diff}도")