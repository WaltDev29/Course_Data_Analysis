# 코드 4-6: 합계, 평균, 표준편차 등 데이터프레임의 기초 통계 메서드를 사용하는 예제

# 코드 4-1 #########################################################
import pandas as pd

df = pd.read_csv("data/iris.csv")  # csv 파일 읽기

# 코드 4-1에 이어서 실행 ############################################

# 데이터프레임의 통계 관련 메서드
# 통계 메서드는 숫자에만 적용되므로 문자열 컬럼인 'Species'를 빼고 df2를 만든다
df2 = df.loc[:, df.columns != 'Species']  # 숫자형 컬럼만 추출

# 아래 메서드들은 기본적으로 컬럼(세로) 방향으로 계산하여 컬럼별 값을 시리즈로 돌려준다
# 행 방향으로 계산하려면 axis=1을 넣는다 (예: df2.sum(axis=1))
print(f'\n[df2.sum()] 값들의 합계\n{df2.sum()}')  # 값들의 합계
print(f'\n[df2.mean()] 값들의 평균\n{df2.mean()}')  # 값들의 평균
print(f'\n[df2.median()] 값들의 중앙값\n{df2.median()}')  # 크기순으로 늘어놓았을 때 한가운데 값
print(f'\n[df2.max()] 값들의 최댓값\n{df2.max()}')  # 값들의 최댓값
print(f'\n[df2.min()] 값들의 최솟값\n{df2.min()}')  # 값들의 최솟값
print(f'\n[df2.std()] 값들의 표준편차\n{df2.std()}')  # 평균에서 흩어진 정도
print(f'\n[df2.var()] 값들의 분산\n{df2.var()}')  # 표준편차의 제곱
print(f'\n[df2.abs()] 값들의 절댓값\n{df2.abs()}')  # 하나의 값이 아니라 원본과 같은 크기의 표를 돌려준다

# describe()는 개수, 평균, 표준편차, 최소/최대, 사분위수를 한 번에 정리해 준다
# 데이터를 처음 받았을 때 가장 먼저 확인하는 요약 정보이다
print(f'\n[df2.describe()] 기초 통계 정보\n{df2.describe()}')
